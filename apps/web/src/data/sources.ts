/** Default clause for an obligation's regulator (overridable with specifics). */
export function sourceForRegulator(reg: Regulator): string {
  switch (reg) {
    case 'PFRDA':
      return 'SRC-PFRDA-ICS-2024'
    case 'CERT-In':
      return 'SRC-CERTIN-2022'
    case 'DPDP':
      return 'SRC-DPDP-2025'
    case 'GST':
      return 'SRC-CGST-47'
    case 'Labour':
      return 'SRC-EPF-14B'
    case 'Companies Act':
      return 'SRC-CA-92-5'
  }
}

/** Standard a framework clause maps to, for per-mapping provenance on controls. */
export function sourceForFramework(fw: Framework): string {
  switch (fw) {
    case 'ISO 27001':
      return 'SRC-ISO-27001'
    case 'NIST CSF':
      return 'SRC-NIST-CSF'
    case 'PCI DSS':
      return 'SRC-PCI-DSS'
    case 'PFRDA ICS':
      return 'SRC-PFRDA-ICS-2024'
  }
}
